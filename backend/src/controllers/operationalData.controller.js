// Operational data: what users and sellers generated by using the app.
// Master data (users, admins, sellers, transporters, providers, categories, products, services, settings) is never touched.
const OPERATIONAL = [
  { key: 'orders', label: 'Store orders', Model: Order },
  { key: 'transportBookings', label: 'Transport bookings', Model: TransportRequest },
  { key: 'sharedRuns', label: 'Shared transport runs', Model: SharedTrip },
  { key: 'transportReviews', label: 'Transport reviews', Model: TransportReview },
  { key: 'serviceBookings', label: 'Service bookings', Model: ServiceRequest },
  { key: 'serviceReviews', label: 'Service reviews', Model: ServiceReview },
  { key: 'enquiries', label: 'Horse enquiries and chats', Model: Inquiry },
  { key: 'visits', label: 'Horse visit requests', Model: VisitRequest },
  { key: 'paymentIntents', label: 'Payment intents', Model: PaymentIntent },
  { key: 'paymentTransactions', label: 'Payment transactions', Model: PaymentTransaction },
  { key: 'refunds', label: 'Refunds', Model: PaymentRefund },
  { key: 'webhookEvents', label: 'Payment webhook events', Model: PaymentWebhookEvent },
  { key: 'userWallets', label: 'User wallets', Model: PaymentUserWallet },
  { key: 'transporterWallets', label: 'Transporter wallets', Model: PaymentTransporterWallet },
  { key: 'providerWallets', label: 'Service provider wallets', Model: PaymentProviderWallet },
  { key: 'storeSellerWallets', label: 'Store seller wallets', Model: PaymentStoreSellerWallet },
  { key: 'horseSellerWallets', label: 'Horse seller wallets', Model: PaymentHorseSellerWallet },
  { key: 'withdrawals', label: 'Transporter withdrawals', Model: WithdrawalRequest },
];

const CONFIRM_PHRASE = 'DELETE OPERATIONAL DATA';

// GET /api/admin/system-settings/developer/operational-data — how many records each group holds
exports.operationalCounts = asyncHandler(async (req, res) => {
  const counts = await Promise.all(OPERATIONAL.map(({ Model }) => Model.countDocuments()));
  res.json({
    groups: OPERATIONAL.map((g, i) => ({ key: g.key, label: g.label, count: counts[i] })),
    total: counts.reduce((s, n) => s + n, 0),
    confirmPhrase: CONFIRM_PHRASE,
  });
});

// POST /api/admin/system-settings/developer/clear-operational-data  { confirm: 'DELETE OPERATIONAL DATA' }
exports.clearOperationalData = asyncHandler(async (req, res) => {
  if (req.body.confirm !== CONFIRM_PHRASE) {
    return res.status(400).json({ message: `Type "${CONFIRM_PHRASE}" to confirm` });
  }

  const deleted = {};
  for (const { key, Model } of OPERATIONAL) {
    const result = await Model.deleteMany({});
    deleted[key] = result.deletedCount || 0;
  }

  // Reset what the removed bookings and payments left behind, without touching the accounts themselves.
  await Promise.all([
    Vehicle.updateMany({}, { isAvailable: true }),
    Driver.updateMany({}, { isAvailable: true }),
    Transporter.updateMany({}, { rating: { average: 0, count: 0 } }),
    Provider.updateMany({}, { rating: { average: 0, count: 0 } }),
  ]);

  res.json({ deleted, total: Object.values(deleted).reduce((s, n) => s + n, 0) });
});
